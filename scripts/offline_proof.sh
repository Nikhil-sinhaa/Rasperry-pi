#!/usr/bin/env bash
# scripts/offline_proof.sh – Member 2: offline processing proof
#
# PURPOSE
# -------
# Demonstrate that the application works with networking fully disabled.
# Two modes are supported:
#   1. unshare -n (Linux namespaces) – completely severs the network namespace.
#   2. Wi-Fi-off fallback – documents must be disabled manually before running.
#
# USAGE
#   bash scripts/offline_proof.sh [--sample SAMPLE_PDF] [--skip-capture]
#
# FLAGS
#   --sample PATH   Path to a sample PDF for the demo (default: samples/sample_contract.pdf)
#   --skip-capture  Skip tcpdump network capture (useful in containers with no tcpdump)
#
# OUTPUT
#   evidence/offline-run.md  – timestamped proof report
#   evidence/network-monitor.txt  – non-loopback traffic (should be empty)
#
# REQUIREMENTS
#   - Ollama is already running locally with OLLAMA_NO_CLOUD=1 and
#     OLLAMA_HOST=127.0.0.1:11434 set in the Ollama server process.
#     Example: OLLAMA_NO_CLOUD=1 OLLAMA_HOST=127.0.0.1:11434 ollama serve
#   - All models have been pulled already (ollama pull …).
#   - The app dependencies are installed (pip install -r requirements.txt).
#   - On Linux: unshare(1) with --net support.  On macOS/Windows: disable networking
#     manually and set OFFLINE_PROOF_NO_UNSHARE=1.
#
# IMPORTANT: Never commit this output file if it contains private document content.

# Redact IP addresses before sharing the network-monitor.txt externally.

set -euo pipefail

SAMPLE_PDF="${SAMPLE_PDF:-samples/sample_contract.pdf}"
SKIP_CAPTURE="${SKIP_CAPTURE:-0}"
EVIDENCE_DIR="evidence"
REPORT_FILE="$EVIDENCE_DIR/offline-run.md"
NETMON_FILE="$EVIDENCE_DIR/network-monitor.txt"
TIMESTAMP="$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
COMMIT="$(git rev-parse --short HEAD 2>/dev/null || echo 'unknown')"

mkdir -p "$EVIDENCE_DIR"

# ---------------------------------------------------------------------------
# Helper: record a step in the report
# ---------------------------------------------------------------------------
log_step() {
  echo "$1" | tee -a "$REPORT_FILE"
}

# ---------------------------------------------------------------------------
# Initialise the report
# ---------------------------------------------------------------------------
cat > "$REPORT_FILE" <<EOF
# Offline Processing Proof
<!-- generated by scripts/offline_proof.sh – do not edit manually -->

| Field         | Value |
|---------------|-------|
| Date/time     | $TIMESTAMP |
| Commit        | $COMMIT |
| Host          | $(hostname) |
| OS            | $(uname -a 2>/dev/null || echo "Windows – see systeminfo") |
| Python        | $(python --version 2>&1) |
| Ollama        | $(ollama --version 2>/dev/null || echo "not in PATH") |
| Sample file   | $SAMPLE_PDF |

## Step 1 – Models installed
EOF

log_step ""
if command -v ollama > /dev/null 2>&1; then
  echo '```' >> "$REPORT_FILE"
  ollama list 2>&1 | tee -a "$REPORT_FILE"
  echo '```' >> "$REPORT_FILE"
else
  log_step "WARNING: ollama not found in PATH; skipping model list."
fi

# ---------------------------------------------------------------------------
# Step 2 – Network capture (background, if tcpdump available and not skipped)
# ---------------------------------------------------------------------------
log_step ""
log_step "## Step 2 – Non-loopback network capture"
CAPTURE_PID=""
if [[ "$SKIP_CAPTURE" == "0" ]] && command -v tcpdump > /dev/null 2>&1; then
  log_step "Starting tcpdump capture to $NETMON_FILE …"
  sudo tcpdump -i any -nn 'not net 127.0.0.0/8 and not host ::1' > "$NETMON_FILE" 2>&1 &
  CAPTURE_PID=$!
  log_step "tcpdump PID: $CAPTURE_PID"
  sleep 2
else
  log_step "tcpdump not available or --skip-capture set. Skipping network capture."
  log_step "Manual alternative: use Wireshark with filter 'not loopback' before running the demo."
  echo "(no automated capture)" > "$NETMON_FILE"
fi

# ---------------------------------------------------------------------------
# Step 3 – Run in an isolated network namespace (Linux only)
# ---------------------------------------------------------------------------
log_step ""
log_step "## Step 3 – Isolated namespace run"

RUN_CMD="python -m streamlit run app.py --server.headless true -- --offline-check"
if [[ "${OFFLINE_PROOF_NO_UNSHARE:-0}" == "1" ]]; then
  log_step "OFFLINE_PROOF_NO_UNSHARE=1: skipping unshare. Ensure Wi-Fi is already off."
  log_step "Starting Streamlit in the current (Wi-Fi-off) network context …"
  log_step "Command: $RUN_CMD"
  # Run for 10 seconds then kill (smoke-test: if it starts, the app works offline)
  timeout 10 $RUN_CMD >> "$REPORT_FILE" 2>&1 || true
  log_step "App exited (expected: timeout or clean exit after smoke test)."
elif command -v unshare > /dev/null 2>&1; then
  log_step "Running inside a new network namespace (unshare -n)."
  log_step "Command: unshare -n $RUN_CMD"
  # Loopback inside the namespace must be brought up first.
  unshare -n bash -c "ip link set lo up && timeout 10 $RUN_CMD" >> "$REPORT_FILE" 2>&1 || true
  log_step "Namespace run complete."
else
  log_step "WARNING: unshare not available (non-Linux?). Set OFFLINE_PROOF_NO_UNSHARE=1 and"
  log_step "disable Wi-Fi/network manually before re-running this script."
fi

# ---------------------------------------------------------------------------
# Step 4 – Static privacy audit
# ---------------------------------------------------------------------------
log_step ""
log_step "## Step 4 – Static privacy audit"
echo '```' >> "$REPORT_FILE"
python scripts/static_privacy_audit.py 2>&1 | tee -a "$REPORT_FILE"
echo '```' >> "$REPORT_FILE"

# ---------------------------------------------------------------------------
# Stop capture and summarise
# ---------------------------------------------------------------------------
if [[ -n "$CAPTURE_PID" ]]; then
  sleep 2
  sudo kill "$CAPTURE_PID" 2>/dev/null || true
  wait "$CAPTURE_PID" 2>/dev/null || true

  log_step ""
  log_step "## Step 5 – Network capture summary"
  LINES=$(wc -l < "$NETMON_FILE" || echo "?")
  log_step "Non-loopback packets captured: $LINES lines in $NETMON_FILE"
  log_step "Expected: 0 lines (empty file means no external traffic)."
  if [[ "$LINES" -gt 0 ]]; then
    log_step "WARNING: non-loopback traffic detected. Review $NETMON_FILE."
    echo '```' >> "$REPORT_FILE"
    head -40 "$NETMON_FILE" >> "$REPORT_FILE"
    echo '```' >> "$REPORT_FILE"
  else
    log_step "PASS: no non-loopback traffic recorded during the offline run."
  fi
fi

log_step ""
log_step "## Result"
log_step "Offline proof script completed at $(date -u '+%Y-%m-%dT%H:%M:%SZ')."
log_step "Review the steps above and confirm each one manually before calling this evidence."
log_step "Never write PASSED for a step you did not actually run."

echo ""
echo "Report written to $REPORT_FILE"
