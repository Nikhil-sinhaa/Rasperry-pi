#!/usr/bin/env bash
# scripts/canary_disk_search.sh – Member 2: canary phrase disk-search proof
#
# PURPOSE
# -------
# Verify that a test document's content does not persist to disk after the app
# processes it.  We embed a unique "canary phrase" in a synthetic test document,
# run the full demo, then search the disk for that phrase.  A match means the
# app (or one of its dependencies) wrote the document content somewhere.
#
# USAGE
#   bash scripts/canary_disk_search.sh [--canary-phrase PHRASE]
#
# FLAGS
#   --canary-phrase TEXT  Override the default unique canary phrase.
#
# OUTPUT
#   evidence/temp-file-check.md  – timestamped report of the disk search

set -euo pipefail

# --------------------------------------------------------------------------
# Configuration
# --------------------------------------------------------------------------
CANARY_PHRASE="${CANARY_PHRASE:-CANARY_LEGAL_TRIAGE_XK7QZ9WV_$(date +%s)}"
EVIDENCE_DIR="evidence"
REPORT_FILE="$EVIDENCE_DIR/temp-file-check.md"
TIMESTAMP="$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
COMMIT="$(git rev-parse --short HEAD 2>/dev/null || echo 'unknown')"
CANARY_PDF="/tmp/canary_test_$$.pdf"   # temporary; cleaned up after search

mkdir -p "$EVIDENCE_DIR"

# --------------------------------------------------------------------------
# Helper
# --------------------------------------------------------------------------
log() {
  echo "$1" | tee -a "$REPORT_FILE"
}

# --------------------------------------------------------------------------
# Initialise report
# --------------------------------------------------------------------------
cat > "$REPORT_FILE" <<EOF
# Canary Disk-Search – Temp-File Check
<!-- generated by scripts/canary_disk_search.sh – do not edit manually -->

| Field          | Value |
|----------------|-------|
| Date/time      | $TIMESTAMP |
| Commit         | $COMMIT |
| Host           | $(hostname) |
| Canary phrase  | $CANARY_PHRASE |

## Step 1 – Create synthetic canary document
EOF

# --------------------------------------------------------------------------
# Step 1: Create a synthetic canary PDF using Python + reportlab or plain text
# --------------------------------------------------------------------------
python - <<PYEOF
import sys, os

canary_phrase = os.environ.get("CANARY_PHRASE", "CANARY_LEGAL_TRIAGE_DEFAULT")
canary_pdf    = os.environ.get("CANARY_PDF", "/tmp/canary_test.pdf")

# Try to build a real PDF with pypdf-compatible content.
# If reportlab is not installed, fall back to a plain .txt.
try:
    from reportlab.pdfgen import canvas
    c = canvas.Canvas(canary_pdf)
    c.drawString(72, 720, "SYNTHETIC TEST DOCUMENT – NOT A REAL CONTRACT")
    c.drawString(72, 700, f"Canary phrase: {canary_phrase}")
    c.drawString(72, 680, "This file was created solely to test that the app does not persist")
    c.drawString(72, 660, "document content to disk.  It contains no private information.")
    c.save()
    print(f"Created PDF canary at {canary_pdf}")
except ImportError:
    # reportlab not installed; fall back to .txt
    txt_path = canary_pdf.replace(".pdf", ".txt")
    with open(txt_path, "w", encoding="utf-8") as f:
        f.write("SYNTHETIC TEST DOCUMENT – NOT A REAL CONTRACT\n")
        f.write(f"Canary phrase: {canary_phrase}\n")
        f.write("This file tests that the app does not persist document content to disk.\n")
    os.rename(txt_path, canary_pdf)  # rename so callers always see the expected path
    print(f"reportlab not installed; created plain-text canary at {canary_pdf}")
PYEOF

log "Canary file created at: $CANARY_PDF"
log "Canary phrase: $CANARY_PHRASE"
log ""

# --------------------------------------------------------------------------
# Step 2: Instruct the tester to run the demo manually
# --------------------------------------------------------------------------
log "## Step 2 – Manual demo step (REQUIRED)"
log ""
log "Upload **$CANARY_PDF** into the running app and run a full triage."
log "Then return here and press Enter to continue the disk search."
log ""
log "Press Enter when the demo is complete …"
read -r _ignored || true   # non-interactive environments skip this

log ""
log "Disk search started at: $(date -u '+%Y-%m-%dT%H:%M:%SZ')"
log ""

# --------------------------------------------------------------------------
# Step 3: Search the disk for the canary phrase
# --------------------------------------------------------------------------
log "## Step 3 – Disk search for canary phrase"
log ""
log "Searching dirs: /tmp, \$HOME, .streamlit/, .ollama/, __pycache__/ …"
log ""

SEARCH_DIRS=(
  "/tmp"
  "$HOME"
  ".streamlit"
)

# Add Ollama data dir (Linux default)
if [[ -d "$HOME/.ollama" ]]; then
  SEARCH_DIRS+=("$HOME/.ollama")
fi

FOUND=0
for dir in "${SEARCH_DIRS[@]}"; do
  if [[ -d "$dir" ]]; then
    log "Searching $dir …"
    matches=$(grep -rl "$CANARY_PHRASE" "$dir" 2>/dev/null || true)
    if [[ -n "$matches" ]]; then
      log "FOUND in $dir:"
      echo "$matches" | tee -a "$REPORT_FILE"
      FOUND=1
    else
      log "  → Not found."
    fi
  fi
done

# Also search the project tree (excluding the canary file itself and .git)
log ""
log "Searching project tree (excluding .git and canary file itself) …"
project_matches=$(grep -rl "$CANARY_PHRASE" . \
  --exclude-dir=.git \
  --exclude="$(basename "$CANARY_PDF")" \
  --exclude="$(basename "$REPORT_FILE")" \
  2>/dev/null || true)
if [[ -n "$project_matches" ]]; then
  log "FOUND in project:"
  echo "$project_matches" | tee -a "$REPORT_FILE"
  FOUND=1
else
  log "  → Not found."
fi

# --------------------------------------------------------------------------
# Step 4: Browser network tab check reminder
# --------------------------------------------------------------------------
log ""
log "## Step 4 – Browser network tab check (manual)"
log ""
log "Open browser DevTools → Network tab, reload the Streamlit page, and confirm"
log "that no requests go to external hosts (all should be to localhost/127.0.0.1)."
log "Screenshot or note the result below."
log ""
log "_Browser network check result: (fill in manually after running)_"
log ""

# --------------------------------------------------------------------------
# Step 5: Clean up the canary file
# --------------------------------------------------------------------------
rm -f "$CANARY_PDF"
log "Canary file removed."

# --------------------------------------------------------------------------
# Result
# --------------------------------------------------------------------------
log ""
log "## Result"
if [[ "$FOUND" -eq 0 ]]; then
  log "PASS: canary phrase not found outside the canary document itself."
  log "The app did not appear to write document content to disk."
else
  log "FAIL: canary phrase was found in one or more unexpected locations (see above)."
  log "Investigate each match before claiming that the app does not write document content to disk."
fi
log ""
log "Completed at: $(date -u '+%Y-%m-%dT%H:%M:%SZ')"
log "Never write PASSED for a check you did not actually run."

echo ""
echo "Report written to $REPORT_FILE"
